def rules_text(c):
    """把参数翻译成可以照着执行的规则"""
    rot = c["universe"].startswith("rot/")
    lev, vt = c["lev_max"], c["vol_tgt"]
    li = []
    if rot:
        _, k, m = c["universe"].split("/")
        li.append(f"<b>选品</b>：每月第一个交易日，在 28 只 1x 指数与行业 ETF 里按过去 {m} 个交易日涨幅取前 {k} 名（涨幅须大于 0，"
                  f"不够 {k} 名的份额拿现金），每名占 1/{k} 资金，持有它当下<b>流动性达标的最高倍数多头杠杆 ETF</b>"
                  "（3x 优先；没有达标的杠杆版就持有 1x 本身）。")
        unit = "该底层"
    else:
        li.append("<b>选品</b>：只做纳指 100 一族（QQQ / QLD / TQQQ），与模型标定的标的一致。")
        unit = "纳指"
    if vt is None:
        li.append(f"<b>常态仓位</b>：敞口恒为{unit} {lev:g} 倍。")
    elif rot:
        _, k, _ = c["universe"].split("/")
        k = int(k)
        e2, e4 = min(lev, vt / .2), min(lev, vt / .4)
        li.append(f"<b>常态仓位</b>：每一名的敞口 = min({lev:g}, {vt * 100:.0f}% ÷ 该底层近 20 日年化波动率) 倍；"
                  f"用 3 倍 ETF 实现时该名权重 = 敞口 ÷ 3 × 1/{k}，其余放 BIL。例如波动率 20% 时敞口 {e2:.2f} 倍、"
                  f"权重 {e2 / 3 / k * 100:.0f}%；波动率 40% 时敞口 {e4:.2f} 倍、权重 {e4 / 3 / k * 100:.0f}%。")
    else:
        e2, e4 = min(lev, vt / .2), min(lev, vt / .4)
        li.append(f"<b>常态仓位</b>：敞口 = min({lev:g}, {vt * 100:.0f}% ÷ 纳指近 20 日年化波动率) 倍纳指；"
                  f"用 TQQQ 实现，权重 = 敞口 ÷ 3，其余放 BIL。例如波动率 20% 时敞口 {e2:.2f} 倍、TQQQ 权重 "
                  f"{e2 / 3 * 100:.0f}%；波动率 40% 时敞口 {e4:.2f} 倍、TQQQ 权重 {e4 / 3 * 100:.0f}%。")
    red = "实心或空心红点" if c["use_ad"] else "实心红点"
    if c["red_hold"]:
        act = "清仓到 BIL" if c["red_mult"] == 0 else f"常态仓位减到 {c['red_mult'] * 100:.0f}%"
        li.append(f"<b>{red}</b>亮起 → 次日开盘{act}，之后 {c['red_hold']} 个交易日内保持；期间再亮就从最后一次重新计数。")
    rel = "或出现实心蓝点" if c["blue_release"] == "perm" else "（蓝点不解锁，只在抄底期内暂时越过）"
    li.append(f"<b>黄点</b>亮起 → 次日开盘清仓并锁定，直到 TDC 回落到 {c['rearm']:g} 以下{rel}。")
    g = []
    if c["tdc_gate"] is not None:
        g.append(f"TDC 高于 {c['tdc_gate']:g} 时常态仓位清零")
    if c["bear_mult"] < 1:
        g.append("纳指处于熊市（收盘低于 200 日均线且均线低于 21 个交易日前）时常态仓位"
                 + ("清零" if c["bear_mult"] == 0 else f"减到 {c['bear_mult'] * 100:.0f}%"))
    if g:
        li.append("<b>闸门</b>：" + "；".join(g) + "。")
    k = c["blue_k"]
    step = "一次满仓" if k == 1 else f"每出现一个蓝点日加 1/{k}，加满 {k} 个为止"
    li.append(f"<b>实心蓝点</b>亮起 → 进入抄底期（最后一个蓝点之后 {c['blue_hold']} 个交易日）：买 TQQQ，{step}，"
              f"满仓 = 纳指 {c['blue_lev']:g} 倍（TQQQ {min(1, c['blue_lev'] / 3) * 100:.0f}%）。抄底期内不看红点、黄点和闸门。"
              + ("" if c["soft_mult"] else "<b>空心蓝点不理会。</b>"))
    li.append("<b>优先级</b>：蓝点抄底 &gt; 黄点锁仓 &gt; 红点 / 闸门 &gt; 常态。所有信号都是 t 日收盘后才知道，t+1 开盘成交。")
    ps = "  ".join(f"{a}={b}" for a, b in c.items())
    return "<ol>" + "".join(f"<li>{x}</li>" for x in li) + f"</ol><p class='param'>参数：{ps}</p>"


def _m(v):
    return f"{v * 100:.1f}%".replace("-", "−")


